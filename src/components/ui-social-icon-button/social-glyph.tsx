// github is drawn 1px larger on each side (22x22 vs 20x20) — deliberate in the
// design, not a squash like the footer's fixed-20px `<img>` precedent.
const SIZES: Record<SocialNetwork, number> = {
  instagram: 20,
  github: 22,
  facebook: 20,
  linkedin: 20,
};

export interface SocialGlyphProps {
  network: SocialNetwork;
}

/** The chip's brand mark: decorative (`aria-hidden`), inked by `currentColor`. */
export function SocialGlyph({ network }: Readonly<SocialGlyphProps>): React.ReactElement {
  const size: number = SIZES[network];
  return (
    <svg
      aria-hidden="true"
      focusable="false"
      fill="none"
      width={size}
      height={size}
      viewBox={`0 0 ${size} ${size}`}
    >
      <path fill="currentColor" d={PATHS[network]} />
    </svg>
  );
}
